/**
 * Initializes the database with realistic seed data if empty, or resets upon user request.
 */
export async function initializeDatabase(forceReset = false): Promise<void> {
  const existingOrg = await db.organizations.count();
  if (existingOrg > 0 && !forceReset) {
    return;
  }

  await db.transaction('rw', [
    db.organizations,
    db.users,
    db.teams,
    db.projects,
    db.epics,
    db.requirements,
    db.userStories,
    db.tasks,
    db.sprints,
    db.issues,
    db.testCases,
    db.documents,
    db.documentVersions,
    db.changeRequests,
    db.meetings,
    db.activities,
    db.notifications,
    db.risks,
    db.researchMetrics,
  ], async () => {
    if (forceReset) {
      await db.organizations.clear();
      await db.users.clear();
      await db.teams.clear();
      await db.projects.clear();
      await db.epics.clear();
      await db.requirements.clear();
      await db.userStories.clear();
      await db.tasks.clear();
      await db.sprints.clear();
      await db.issues.clear();
      await db.testCases.clear();
      await db.documents.clear();
      await db.documentVersions.clear();
      await db.changeRequests.clear();
      await db.meetings.clear();
      await db.activities.clear();
      await db.notifications.clear();
      await db.risks.clear();
      await db.researchMetrics.clear();
    }

    await db.organizations.add(SEED_ORGANIZATION);
    await db.users.bulkAdd(SEED_USERS);
    await db.teams.bulkAdd(SEED_TEAMS);
    await db.projects.bulkAdd(SEED_PROJECTS);
    await db.epics.bulkAdd(SEED_EPICS);
    await db.requirements.bulkAdd(SEED_REQUIREMENTS);
    await db.userStories.bulkAdd(SEED_USER_STORIES);
    await db.tasks.bulkAdd(SEED_TASKS);
    await db.sprints.bulkAdd(SEED_SPRINTS);
    await db.issues.bulkAdd(SEED_ISSUES);
    await db.testCases.bulkAdd(SEED_TEST_CASES);
    await db.documents.bulkAdd(SEED_DOCUMENTS);
    await db.documentVersions.bulkAdd(SEED_DOCUMENT_VERSIONS);
    await db.changeRequests.bulkAdd(SEED_CHANGE_REQUESTS);
    await db.meetings.bulkAdd(SEED_MEETINGS);
    await db.activities.bulkAdd(SEED_ACTIVITIES);
    await db.notifications.bulkAdd(SEED_NOTIFICATIONS);
    await db.risks.bulkAdd(SEED_RISKS);
  });
}
